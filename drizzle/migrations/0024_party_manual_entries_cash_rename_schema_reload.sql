-- 1. Party manual ledger entries (same pattern as transporter_manual_entries in 0021) ---------------------------
-- Ledger convention for PARTIES is unchanged: DEBIT = amount owed TO Gokul goes up (receivable),
-- CREDIT = amount owed to Gokul goes down (receipt) / Gokul owes more. balance = debit - credit (positive = Receivable).
CREATE TABLE IF NOT EXISTS public.party_manual_entries (
  id uuid PRIMARY KEY,                                   -- generated by the browser once per form, so a retry cannot duplicate
  business_id uuid NOT NULL REFERENCES public.businesses(id),
  party_id uuid NOT NULL REFERENCES public.parties(id),
  entry_date date NOT NULL,
  entry_side text NOT NULL CHECK (entry_side IN ('debit','credit')),
  amount numeric(14,2) NOT NULL CHECK (amount > 0),
  reference text,
  notes text NOT NULL CHECK (length(trim(notes)) >= 3),
  is_reversed boolean NOT NULL DEFAULT false,
  reversal_reason text,
  created_by uuid, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS party_manual_entries_idx ON public.party_manual_entries(business_id, party_id, entry_date);
